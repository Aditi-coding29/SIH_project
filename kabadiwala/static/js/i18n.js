let currentLang = 'en';

function setLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('kc_lang', lang);

  // Update elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[lang][key];
      } else {
        el.innerHTML = translations[lang][key];
      }
    }
  });

  // Trigger language change event if needed
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function t(key) {
  return (translations[currentLang] && translations[currentLang][key]) || (translations['en'] && translations['en'][key]) || key;
}

// Initialize on DOM load
document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('kc_lang') || 'en';
  const selector = document.getElementById('langSelect');
  if (selector) {
    selector.value = saved;
    selector.addEventListener('change', (e) => setLanguage(e.target.value));
  }
  setLanguage(saved);
});

